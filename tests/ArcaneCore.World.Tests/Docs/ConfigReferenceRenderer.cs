using System.Text;
using ArcaneCore.Kernel.Configuration.Conf;
using ArcaneCore.World.Reload;

namespace ArcaneCore.World.Tests.Docs;

/// <summary>The production catalog (every options section of the four assemblies) and the page rendered from it.</summary>
internal static class ConfigProduction
{
    private static readonly Lazy<ConfigCatalogResult> Cached = new(BuildCatalog);

    public static ConfigCatalogResult Catalog => Cached.Value;

    /// <summary>The text of every .cs file under src and tools, excluding build output.</summary>
    public static IReadOnlyList<(string Path, string Text)> SourceFiles()
    {
        string root = RepoRoot.Find();
        var files = new List<(string, string)>();
        foreach (string top in new[] { "src", "tools" })
        {
            string dir = Path.Combine(root, top);
            foreach (string file in Directory.EnumerateFiles(dir, "*.cs", SearchOption.AllDirectories))
            {
                string relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (relative.Contains("/obj/", StringComparison.Ordinal) || relative.Contains("/bin/", StringComparison.Ordinal))
                {
                    continue;
                }

                files.Add((relative, File.ReadAllText(file)));
            }
        }

        return files;
    }

    private static ConfigCatalogResult BuildCatalog()
    {
        var summaries = new ConfigSourceSummaries(SourceFiles().Select(f => f.Text));
        Dictionary<string, string> reload = WorldConfigKeys.All.ToDictionary(k => k.Path, k => k.Live ? "live" : "restart", StringComparer.Ordinal);
        ConfigCatalogResult catalog = ConfigCatalog.Build(
            ConfigExceptionTable.Sections(),
            summaries.Find,
            ConfigDocOverrides.Texts,
            ConfigExceptionTable.SkippedProperties,
            path => reload.GetValueOrDefault(path));

        // OwnerNode resolves Environment.MachineName at runtime. Keep the generated catalog deterministic and leave the
        // key unset in .conf.dist so binding preserves that runtime identity on each host.
        return catalog with
        {
            Entries = [.. catalog.Entries.Select(entry => entry.Path == "Cluster:Fencing:OwnerNode"
                ? entry with { Default = "\"<machine-name>\"", RawDefault = null }
                : entry)]
        };
    }
}

/// <summary>Renders <c>docs/reference/configuration.md</c>.</summary>
internal static class ConfigReferenceRenderer
{
    public static string Render(IReadOnlyList<ConfigEntry> entries, IReadOnlyList<AdHocKey> adHoc, IReadOnlyDictionary<string, string> skipped)
    {
        var sb = new StringBuilder();
        sb.Append("# Configuration reference\n\n");
        sb.Append("<!-- GENERATED by tests/ArcaneCore.World.Tests/Docs (ConfigReferenceRenderer) from the options classes. Do not edit by hand.\n");
        sb.Append("     Regenerate: ").Append(DocsGolden.RegenerateCommand).Append(" -->\n\n");
        sb.Append("Both daemons build their configuration with the .NET generic host defaults: `appsettings.json` from the content root (the working directory the daemon starts in), then environment variables, then command-line arguments. ");
        sb.Append("The environment variable for a key is the key with each `:` replaced by `__` (a command-line argument uses `--Section:Key=value`), for example `World:GmCommands:LowerSecurity` is `World__GmCommands__LowerSecurity`. ");
        sb.Append("`ArcaneCore.World.exe check-config` validates the result and the daemon runs the same check at every start (exit code 78 when invalid).\n\n");
        sb.Append("How to read the tables:\n\n");
        sb.Append("- **Default** is the value of a freshly constructed options object, so it cannot disagree with the code. ");
        sb.Append("A section that is absent from the file simply keeps every default.\n");
        sb.Append("- **Reload** is what `.reload config` does with a `World` key: `live` is applied to the running server, `restart` keeps its value until the next start (and logs that it could not change). ");
        sb.Append("`-` means the key is not part of the `.reload config` set (see docs/areas/hot-reload.md).\n");
        sb.Append("- **Meaning** is the `///` summary of the property in the source, which also carries the retail (vmangos) reference where one exists. ");
        sb.Append("Where a property has no summary yet, the text comes from the documentation overrides in the docs tests, never from this page.\n");
        sb.Append("- A default that is not the retail behaviour is called out in its meaning where the source records it. The release caveats of the opt-in hardening switches are in docs/security/hardening.md.\n\n");

        string[] sections = [.. entries.Select(e => e.Section).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];
        sb.Append("## Sections\n\n");
        foreach (string section in sections)
        {
            sb.Append("- [`").Append(section).Append("`](#").Append(Anchor(section)).Append(")\n");
        }

        bool hasElementFields = entries.Any(e => e.ElementFields is { Count: > 0 });
        if (hasElementFields)
        {
            sb.Append("- [List and map element fields](#list-and-map-element-fields)\n");
        }

        sb.Append("- [Keys read by name](#keys-read-by-name)\n- [Aliases and framework sections](#aliases-and-framework-sections)\n\n");

        foreach (string section in sections)
        {
            sb.Append("## `").Append(section).Append("`\n\n");
            sb.Append("| Key | Type | Default | Reload | Meaning |\n|---|---|---|---|---|\n");
            foreach (ConfigEntry entry in entries.Where(e => e.Section == section))
            {
                sb.Append("| `").Append(entry.Path).Append("` | `").Append(entry.TypeText).Append("` | ")
                    .Append(Code(entry.Default)).Append(" | ").Append(entry.Reload).Append(" | ").Append(entry.Meaning).Append(" |\n");
            }

            sb.Append('\n');
        }

        if (hasElementFields)
        {
            RenderElementFields(sb, entries);
        }

        sb.Append("## Keys read by name\n\n");
        sb.Append("These keys are read directly rather than through an options class.\n\n| Key | Type | Default | Meaning |\n|---|---|---|---|\n");
        foreach (AdHocKey key in adHoc.OrderBy(k => k.Path, StringComparer.Ordinal))
        {
            sb.Append("| `").Append(key.Path).Append("` | `").Append(key.TypeText).Append("` | `").Append(key.Default).Append("` | ").Append(key.Meaning).Append(" |\n");
        }

        sb.Append("\n## Aliases and framework sections\n\n");
        foreach (KeyValuePair<string, string> alias in skipped.OrderBy(a => a.Key, StringComparer.Ordinal))
        {
            sb.Append("- `").Append(alias.Key).Append("`: ").Append(alias.Value).Append('\n');
        }

        sb.Append("- `Logging` (for example `Logging:LogLevel:<category>`) and `HostOptions` (`HostOptions:ShutdownTimeout`) belong to the .NET host, not to ArcaneCore; see the .NET documentation for their keys. "
            + "The checks accept every key below them and never report one as unknown; `Logging:ArcaneCore` is not part of this and is documented above.\n");
        sb.Append("- `hostBuilder:reloadConfigOnChange` is a .NET host key that ArcaneCore reads when it attaches the `.conf` file: `true` (the default when unset or unparsable) makes a running daemon watch `world.conf`, `realm.conf` or `gateway.conf` and pick up an edit, ")
            .Append("`false` reads the file once at start. It also governs the `appsettings*.json` files.\n");
        return sb.ToString();
    }

    /// <summary>The fields of one entry of every list or map option whose entries are groups of keys (a key table cannot show them: it has one row per option).</summary>
    private static void RenderElementFields(StringBuilder sb, IReadOnlyList<ConfigEntry> entries)
    {
        sb.Append("## List and map element fields\n\n");
        sb.Append("These options hold entries that are themselves groups of keys. A list entry is numbered (`Key:0:Field`, `Key:1:Field`, ...), a map entry is named (`Key:name:Field`); in a `.conf` file the separator is a dot (`Key.0.Field = value`). ");
        sb.Append("A field that is not written keeps the default shown here.\n\n");
        foreach (ConfigEntry entry in entries.Where(e => e.ElementFields is { Count: > 0 }).OrderBy(e => e.Path, StringComparer.Ordinal))
        {
            string selector = entry.Kind == ConfKey.Map ? "<name>" : "<index>";
            sb.Append("### `").Append(entry.Path).Append("`\n\n");
            sb.Append("`").Append(entry.TypeText).Append("`: each entry sets `").Append(entry.Path).Append(':').Append(selector).Append(":<Field>`.\n\n");
            sb.Append("| Field | Type | Default | Meaning |\n|---|---|---|---|\n");
            foreach (ConfigElementField field in entry.ElementFields!)
            {
                sb.Append("| `").Append(field.Name).Append("` | `").Append(field.TypeText).Append("` | ").Append(Code(field.Default)).Append(" | ").Append(field.Meaning).Append(" |\n");
            }

            sb.Append('\n');
        }
    }

    private static string Code(string value) => value.Contains('|', StringComparison.Ordinal) ? "`" + value.Replace("|", "\\|", StringComparison.Ordinal) + "`" : "`" + value + "`";

    /// <summary>The GitHub heading anchor of a heading made of one code span.</summary>
    internal static string Anchor(string heading)
    {
        var sb = new StringBuilder();
        foreach (char c in heading.ToLowerInvariant())
        {
            if (char.IsLetterOrDigit(c) || c == '-' || c == '_')
            {
                sb.Append(c);
            }
            else if (c == ' ')
            {
                sb.Append('-');
            }
        }

        return sb.ToString();
    }
}
