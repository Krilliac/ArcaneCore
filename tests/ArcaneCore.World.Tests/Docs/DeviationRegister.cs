namespace ArcaneCore.World.Tests.Docs;

/// <summary>How a key's default relates to the retail (vmangos) behaviour.</summary>
internal enum Stance
{
    /// <summary>The default is the retail behaviour; the key only exists so an operator can opt into something stricter.</summary>
    OptIn,

    /// <summary>The default is NOT the retail behaviour: the retail value is what an operator sets for parity.</summary>
    NonRetailDefault,

    /// <summary>A development switch that is off by default.</summary>
    DevelopmentOnly,
}

/// <summary>One release-note entry: a key an operator should decide on before exposing a realm.</summary>
internal sealed record Deviation(string Key, string Default, Stance Stance, string Retail, string Advice);

