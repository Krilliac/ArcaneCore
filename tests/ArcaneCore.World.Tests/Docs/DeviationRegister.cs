    /// <summary>The markdown table the guide embeds between <see cref="Begin"/> and <see cref="End"/>.</summary>
    public static string Block()
    {
        var sb = new StringBuilder();
        sb.Append(Begin).Append('\n');
        sb.Append("| Key | Default | Default is | Retail (vmangos) | What to do |\n|---|---|---|---|---|\n");
        foreach (Deviation d in All)
        {
            string stance = d.Stance switch
            {
                Stance.NonRetailDefault => "**not retail**",
                Stance.DevelopmentOnly => "development only",
                _ => "retail",
            };
            sb.Append("| `").Append(d.Key).Append("` | `").Append(d.Default).Append("` | ").Append(stance).Append(" | ").Append(d.Retail).Append(" | ").Append(d.Advice).Append(" |\n");
        }

        sb.Append(End);
        return sb.ToString();
    }

    /// <summary>The guide text with its register block replaced by <see cref="Block"/> (used when the docs are regenerated).</summary>
    public static string Replace(string guide)
    {
        string normalized = guide.Replace("\r\n", "\n", StringComparison.Ordinal);
        int begin = normalized.IndexOf(Begin, StringComparison.Ordinal);
        int end = normalized.IndexOf(End, StringComparison.Ordinal);
        if (begin < 0 || end < begin)
        {
            throw new InvalidOperationException("the guide has no register block markers");
        }

        return normalized[..begin] + Block() + normalized[(end + End.Length)..];
    }
