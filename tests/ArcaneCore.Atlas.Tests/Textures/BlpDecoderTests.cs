using ArcaneCore.Atlas.Textures;
using Xunit;

namespace ArcaneCore.Atlas.Tests.Textures;

/// <summary>
/// BLP2 decoding over files built byte by byte (<see cref="BlpTestWriter"/>). The format rules are the design's section 2.1
/// (wowdev.wiki BLP2): palettized alpha comes from <c>alphaDepth</c> only (the palette's own alpha byte and <c>alphaType</c> are
/// ignored), DXT1 honours the 3-colour transparent index only when <c>alphaDepth</c> is 1, <c>hasMips</c> is "levels listed" for
/// any non-zero value, a level is valid only when it lies inside the file and has the exact encoded size, and a missing or
/// truncated chain is regenerated by a box filter.
/// </summary>
public sealed class BlpDecoderTests
{
    private static readonly BlpTestWriter.Px[] Palette4 =
    [
        new(255, 0, 0), new(0, 255, 0), new(0, 0, 255), new(200, 100, 50),
    ];

    private static void AssertPixel(RgbaImage image, int x, int y, BlpTestWriter.Px expected)
    {
        Rgba actual = image.Get(x, y);
        Assert.True(
            expected.R == actual.R && expected.G == actual.G && expected.B == actual.B && expected.A == actual.A,
            $"pixel ({x},{y}): expected {expected}, got ({actual.R},{actual.G},{actual.B},{actual.A})");
    }

    [Theory]
    [InlineData((byte)8)]
    [InlineData((byte)2)]
    [InlineData((byte)4)]
    [InlineData((byte)0)]
    public void Palettized_NoAlpha_IsOpaque_WhateverAlphaTypeAndPaletteAlphaSay(byte alphaType)
    {
        // The palette's alpha byte is 0 on purpose: a decoder that used it would return a transparent image.
        byte[] file = BlpTestWriter.Palettized(2, 2, Palette4, [0, 1, 2, 3], alphaDepth: 0, alphaPlane: null, alphaType: alphaType, paletteAlphaByte: 0);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.False(image.HasAlpha);
        Assert.False(image.Alpha1Bit);
        AssertPixel(image.Levels[0], 0, 0, new(255, 0, 0));
        AssertPixel(image.Levels[0], 1, 0, new(0, 255, 0));
        AssertPixel(image.Levels[0], 0, 1, new(0, 0, 255));
        AssertPixel(image.Levels[0], 1, 1, new(200, 100, 50));
    }

    [Fact]
    public void Palettized_EightBitAlpha_ReadsOneByteAlphaPerPixel()
    {
        byte[] file = BlpTestWriter.Palettized(2, 2, Palette4, [0, 1, 2, 3], alphaDepth: 8, alphaPlane: [0, 64, 128, 255], alphaType: 8);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.True(image.HasAlpha);
        Assert.False(image.Alpha1Bit);
        AssertPixel(image.Levels[0], 0, 0, new(255, 0, 0, 0));
        AssertPixel(image.Levels[0], 1, 0, new(0, 255, 0, 64));
        AssertPixel(image.Levels[0], 0, 1, new(0, 0, 255, 128));
        AssertPixel(image.Levels[0], 1, 1, new(200, 100, 50, 255));
    }

    [Fact]
    public void Palettized_OneBitAlpha_IsEightPixelsPerByte_LeastSignificantBitFirst()
    {
        // 8x2: row 0 byte 0b00000101 -> pixels 0 and 2 opaque; row 1 byte 0b10000000 -> pixel 7 of the row opaque.
        byte[] indices = [.. Enumerable.Repeat((byte)0, 16)];
        byte[] file = BlpTestWriter.Palettized(8, 2, Palette4, indices, alphaDepth: 1, alphaPlane: [0x05, 0x80], alphaType: 8);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.True(image.HasAlpha);
        Assert.True(image.Alpha1Bit);
        int[] row0 = [255, 0, 255, 0, 0, 0, 0, 0];
        int[] row1 = [0, 0, 0, 0, 0, 0, 0, 255];
        for (int x = 0; x < 8; x++)
        {
            Assert.Equal(row0[x], image.Levels[0].Get(x, 0).A);
            Assert.Equal(row1[x], image.Levels[0].Get(x, 1).A);
        }
    }

    [Fact]
    public void Palettized_FourBitAlpha_IsTwoPixelsPerByte_LowNibbleFirst_ScaledBy17()
    {
        // 4x2 = 8 pixels = 4 bytes: nibbles 0,5 | 10,15 | 1,2 | 8,15 (low nibble first).
        byte[] file = BlpTestWriter.Palettized(4, 2, Palette4, [0, 0, 0, 0, 0, 0, 0, 0], alphaDepth: 4, alphaPlane: [0x50, 0xFA, 0x21, 0xF8], alphaType: 8);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.True(image.HasAlpha);
        Assert.Equal([0, 85, 170, 255], new int[] { image.Levels[0].Get(0, 0).A, image.Levels[0].Get(1, 0).A, image.Levels[0].Get(2, 0).A, image.Levels[0].Get(3, 0).A });
        Assert.Equal([17, 34, 136, 255], new int[] { image.Levels[0].Get(0, 1).A, image.Levels[0].Get(1, 1).A, image.Levels[0].Get(2, 1).A, image.Levels[0].Get(3, 1).A });
    }

    [Fact]
    public void Raw_Bgra_IsSwizzledToRgba()
    {
        byte[] file = BlpTestWriter.Raw(2, 1, [10, 20, 30, 40, 50, 60, 70, 80], alphaDepth: 8);

        BlpImage image = BlpDecoder.Decode(file);

        AssertPixel(image.Levels[0], 0, 0, new(30, 20, 10, 40));
        AssertPixel(image.Levels[0], 1, 0, new(70, 60, 50, 80));
    }

    [Fact]
    public void Dxt1_AlphaDepthZero_IsForcedOpaque_AlphaDepthOneKeepsTheTransparentIndex()
    {
        byte[] block = [0x00, 0x00, 0x00, 0x40, 0xE4, 0x1B, 0x00, 0xFF]; // c0 0x0000 < c1 0x4000, rows [0,1,2,3] [3,2,1,0] [0..] [3..]
        BlpImage opaque = BlpDecoder.Decode(BlpTestWriter.Dxt(4, 4, alphaType: 0, alphaDepth: 0, [block]));
        BlpImage keyed = BlpDecoder.Decode(BlpTestWriter.Dxt(4, 4, alphaType: 0, alphaDepth: 1, [block]));

        Assert.False(opaque.HasAlpha);
        AssertPixel(opaque.Levels[0], 3, 0, new(0, 0, 0, 255));
        Assert.True(keyed.HasAlpha);
        Assert.True(keyed.Alpha1Bit);
        AssertPixel(keyed.Levels[0], 3, 0, new(0, 0, 0, 0));
        AssertPixel(keyed.Levels[0], 2, 0, new(33, 0, 0, 255));
    }

    [Fact]
    public void Dxt3AndDxt5_FilesDecodeWithTheirAlphaBlocks()
    {
        byte[] colour = [0x00, 0xF8, 0x1F, 0x00, 0xE4, 0x1B, 0x00, 0xFF];
        byte[] dxt3Alpha = [0x50, 0xFA, 0xAF, 0x05, 0x88, 0x88, 0x21, 0x43];
        byte[] dxt5Alpha = [0x46, 0x00, 0x88, 0xC6, 0xFA, 0x77, 0x39, 0x05];

        BlpImage dxt3 = BlpDecoder.Decode(BlpTestWriter.Dxt(4, 4, alphaType: 1, alphaDepth: 8, [[.. dxt3Alpha, .. colour]]));
        BlpImage dxt5 = BlpDecoder.Decode(BlpTestWriter.Dxt(4, 4, alphaType: 7, alphaDepth: 8, [[.. dxt5Alpha, .. colour]]));

        AssertPixel(dxt3.Levels[0], 1, 0, new(0, 0, 255, 85));
        AssertPixel(dxt3.Levels[0], 3, 0, new(85, 0, 170, 255));
        AssertPixel(dxt5.Levels[0], 0, 0, new(255, 0, 0, 70));
        AssertPixel(dxt5.Levels[0], 2, 0, new(170, 0, 85, 60));
    }

    [Theory]
    [InlineData((byte)1)]
    [InlineData((byte)2)]
    public void ListedMipChain_IsDecodedLevelByLevel_ForAnyNonZeroHasMips(byte hasMips)
    {
        // 4x4 -> 2x2 -> 1x1, each level its own colour so a wrong level is visible.
        var levels = new List<BlpTestWriter.PaletteLevel> { new([1, 1, 1, 1], null), new([2], null) };
        byte[] file = BlpTestWriter.Palettized(4, 4, Palette4, [.. Enumerable.Repeat((byte)0, 16)], alphaDepth: 0, alphaPlane: null, hasMips: hasMips, moreLevels: levels);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.Equal(3, image.Header.ValidLevelCount);
        Assert.Equal(3, image.Levels.Count);
        Assert.Equal((4, 4), (image.Levels[0].Width, image.Levels[0].Height));
        Assert.Equal((2, 2), (image.Levels[1].Width, image.Levels[1].Height));
        Assert.Equal((1, 1), (image.Levels[2].Width, image.Levels[2].Height));
        AssertPixel(image.Levels[0], 3, 3, new(255, 0, 0));
        AssertPixel(image.Levels[1], 1, 1, new(0, 255, 0));
        AssertPixel(image.Levels[2], 0, 0, new(0, 0, 255));
    }

    [Fact]
    public void NoMips_AreGeneratedByABoxFilter_DownToOneByOne()
    {
        // 4x4 grey ramp so every 2x2 average is exact: top-left block (0,100,100,200) -> 100.
        var grey = new BlpTestWriter.Px[256];
        for (int i = 0; i < 256; i++)
        {
            grey[i] = new((byte)i, (byte)i, (byte)i);
        }

        byte[] indices =
        [
            0, 100, 20, 20,
            100, 200, 20, 20,
            40, 40, 60, 60,
            40, 40, 60, 60,
        ];
        byte[] file = BlpTestWriter.Palettized(4, 4, grey, indices, alphaDepth: 0, alphaPlane: null, hasMips: 0);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.Equal(1, image.Header.ValidLevelCount);
        Assert.Equal(3, image.Levels.Count);
        AssertPixel(image.Levels[1], 0, 0, new(100, 100, 100));
        AssertPixel(image.Levels[1], 1, 0, new(20, 20, 20));
        AssertPixel(image.Levels[1], 0, 1, new(40, 40, 40));
        AssertPixel(image.Levels[1], 1, 1, new(60, 60, 60));
        AssertPixel(image.Levels[2], 0, 0, new(55, 55, 55));
    }

    [Fact]
    public void GarbageMipEntries_StopTheChainAtTheFirstInvalidLevel_AndTheRestIsGenerated()
    {
        // hasMips = 1 but level 1 points far outside the file: only level 0 is valid, levels 1.. come from the box filter.
        byte[] file = BlpTestWriter.Palettized(4, 4, Palette4, [.. Enumerable.Repeat((byte)2, 16)], alphaDepth: 0, alphaPlane: null, hasMips: 1);
        file = BlpTestWriter.WithMipEntry(file, 1, offset: 0x7FFFFFF0, size: 4);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.Equal(1, image.Header.ValidLevelCount);
        Assert.Equal(3, image.Levels.Count);
        AssertPixel(image.Levels[1], 0, 0, new(0, 0, 255));
        AssertPixel(image.Levels[2], 0, 0, new(0, 0, 255));
    }

    [Fact]
    public void AMipWithTheWrongSize_IsInvalid_EvenInsideTheFile()
    {
        // Level 1 of a 4x4 palettized file must be 2x2 = 4 bytes. Declaring 3 bytes (inside the file) invalidates it.
        var levels = new List<BlpTestWriter.PaletteLevel> { new([1, 1, 1, 1], null), new([2], null) };
        byte[] file = BlpTestWriter.Palettized(4, 4, Palette4, [.. Enumerable.Repeat((byte)0, 16)], alphaDepth: 0, alphaPlane: null, hasMips: 1, moreLevels: levels);
        file = BlpTestWriter.WithMipEntry(file, 1, offset: (uint)(BlpTestWriter.HeaderBytes + BlpTestWriter.PaletteBytes + 16), size: 3);

        BlpFile header = BlpFile.Parse(file);

        Assert.Equal(1, header.ValidLevelCount);
    }

    [Fact]
    public void NonPowerOfTwoSizes_ChainEndsAtOneByOne()
    {
        // 3x5: level i is max(1, w >> i) x max(1, h >> i): 3x5, 1x2, 1x1.
        byte[] file = BlpTestWriter.Palettized(3, 5, Palette4, [.. Enumerable.Repeat((byte)1, 15)], alphaDepth: 0, alphaPlane: null, hasMips: 0);

        BlpImage image = BlpDecoder.Decode(file);

        Assert.Equal([(3, 5), (1, 2), (1, 1)], image.Levels.Select(l => (l.Width, l.Height)).ToArray());
        AssertPixel(image.Levels[2], 0, 0, new(0, 255, 0));
    }

    [Fact]
    public void Header_ExposesTheEncodingFields()
    {
        byte[] file = BlpTestWriter.Palettized(8, 2, Palette4, [.. Enumerable.Repeat((byte)0, 16)], alphaDepth: 1, alphaPlane: [0, 0], alphaType: 4, hasMips: 2);

        BlpFile header = BlpFile.Parse(file);

        Assert.Equal(1, header.Compression);
        Assert.Equal(1, header.AlphaDepth);
        Assert.Equal(4, header.AlphaType);
        Assert.Equal(2, header.HasMips);
        Assert.Equal(8, header.Width);
        Assert.Equal(2, header.Height);
    }

    [Fact]
    public void LevelData_IsTheFilesOwnBytes_ForPassthrough()
    {
        byte[] block = [0x00, 0xF8, 0x1F, 0x00, 0xE4, 0x1B, 0x00, 0xFF];
        BlpFile header = BlpFile.Parse(BlpTestWriter.Dxt(4, 4, alphaType: 0, alphaDepth: 0, [block]));

        Assert.Equal(block, header.LevelData(0));
    }

    [Fact]
    public void JpegBlp_IsRejectedWithAReason()
    {
        byte[] file = BlpTestWriter.WithType(BlpTestWriter.Palettized(2, 2, Palette4, [0, 0, 0, 0], 0, null), 0);

        InvalidDataException error = Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode(file));

        Assert.Contains("jpeg", error.Message, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void BadMagic_Truncation_AndUnknownCompression_AreInvalidData()
    {
        byte[] good = BlpTestWriter.Palettized(2, 2, Palette4, [0, 1, 2, 3], 0, null);
        byte[] blp1 = (byte[])good.Clone();
        blp1[3] = (byte)'1';
        byte[] unknownCompression = (byte[])good.Clone();
        unknownCompression[8] = 4;

        Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode(blp1));
        Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode(good[..100]));
        Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode(good[..^1]));
        Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode([]));
        Assert.Throws<InvalidDataException>(() => BlpDecoder.Decode(unknownCompression));
    }

    [Theory]
    [InlineData(0, 4)]
    [InlineData(4, 0)]
    [InlineData(4097, 1)]
    [InlineData(1, 4097)]
    public void SizesOutsideOneTo4096_AreRejected_BeforeAnyAllocation(int width, int height)
    {
        byte[] file = BlpTestWriter.Palettized(4, 4, Palette4, [.. Enumerable.Repeat((byte)0, 16)], 0, null);
        System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(file.AsSpan(12), (uint)width);
        System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(file.AsSpan(16), (uint)height);

        Assert.Throws<InvalidDataException>(() => BlpFile.Parse(file));
    }
}
